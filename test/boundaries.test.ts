import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

import { describe, expect, it } from 'vitest';

const ROOT = new URL('..', import.meta.url).pathname;

function files(directory: string): string[] {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

const sources = files(join(ROOT, 'src')).filter((path) => /\.(ts|tsx|mts|mjs|js)$/.test(path) && !path.includes('/generated/'));

describe('boundaries', () => {
  it('every module under src/server starts with server-only', () => {
    const server = sources.filter((path) => path.includes('/src/server/'));
    expect(server.length).toBeGreaterThan(0);
    for (const path of server) {
      const firstStatement = readFileSync(path, 'utf8')
        .split('\n')
        .find((line) => line.trim() !== '' && !line.trim().startsWith('//'));
      expect(firstStatement, relative(ROOT, path)).toBe("import 'server-only';");
    }
  });

  it('no code outside src/server calls fetch or reads the backend address', () => {
    for (const path of sources.filter((p) => !p.includes('/src/server/'))) {
      const text = readFileSync(path, 'utf8');
      expect(text, relative(ROOT, path)).not.toMatch(/\bfetch\(|GMSHIELD_BACKEND_URL|openapi-fetch/);
    }
  });

  it('no NEXT_PUBLIC_ variable exists', () => {
    for (const path of [...sources, join(ROOT, 'next.config.ts')]) {
      expect(readFileSync(path, 'utf8'), relative(ROOT, path)).not.toContain('NEXT_PUBLIC_');
    }
  });

  it('no hand-written type describes a backend request or response', () => {
    const generated = readFileSync(join(ROOT, 'src/server/backend/generated/public.d.ts'), 'utf8');
    expect(generated).toContain('auto-generated by openapi-typescript');
    for (const path of sources) {
      const text = readFileSync(path, 'utf8');
      expect(text, relative(ROOT, path)).not.toMatch(/\b(type|interface)\s+(ContractVersion|Problem)\b/);
    }
  });
});
